export const LANGUAGES: ReadonlyArray<{ id: LanguageSetting; label: string }> = [
  { id: 'system', label: 'System language' },
  { id: 'en', label: 'English' },
  { id: 'es', label: 'Español' },
  { id: 'de', label: 'Deutsch' },
  { id: 'fr', label: 'Français' },
  { id: 'tr', label: 'Türkçe' },
];

const SUPPORTED: ResolvedLanguage[] = ['en', 'es', 'de', 'fr', 'tr'];

export function normalizeLanguage(value: string | undefined): ResolvedLanguage {
  const base = (value ?? 'en').toLowerCase().split('-')[0];
  return SUPPORTED.find(language => language === base) ?? 'en';
}

export function systemLanguage(): ResolvedLanguage {
  if (typeof navigator === 'undefined') return 'en';
  return normalizeLanguage(navigator.languages?.[0] || navigator.language);
}

export function resolveLanguage(setting: LanguageSetting): ResolvedLanguage {
  return setting === 'system' ? systemLanguage() : setting;
}

export function languageLabel(id: LanguageSetting, t?: (key: string) => string): string {
  if (id === 'system') {
    const label = t ? t('System language') : (LANGUAGES[0]?.label ?? 'System language');
    return `${label} (${systemLanguage().toUpperCase()})`;
  }
  return LANGUAGES.find(language => language.id === id)?.label ?? id;
}

