export function makeI18n(language: ResolvedLanguage): I18nValue {
  const catalog =
    language === 'en'
      ? {}
      : {
          ...translations[language],
          ...supplement[language],
          ...mediaAndTorrent[language],
          ...privacyCopy[language],
          ...serviceCopy[language],
        };
  return {
    language,
    locale: language,
    t: (key, vars) => interpolate(catalog[key] ?? key, vars),
  };
}

/**
 * Extension results are produced in the main process, so their stable English
 * messages are translated here instead of leaking English toasts into a
 * localized UI. Names come from the extension manifest and stay untouched.
 */
export function extensionMessage(t: I18nValue['t'], message: string): string {
  // Stable catalogue messages win before the dynamic-name patterns, so
  // "The extension could not be installed." is never read as a name.
  const direct = t(message);
  if (direct !== message) return direct;
  const http = /^Chrome Web Store returned HTTP (\d+)\.$/.exec(message);
  if (http) return t('Chrome Web Store returned HTTP {status}.', { status: http[1] ?? '' });
  const dynamic = /^(.+) (installed|enabled|disabled|removed)\.$/.exec(message);
  if (dynamic) {
    return t(`{name} ${dynamic[2]}.`, { name: dynamic[1] ?? '' });
  }
  return message;
}

