const I18nContext = createContext<I18nValue>(makeI18n('en'));

export function I18nProvider({ value, children }: { value: I18nValue; children: ReactNode }) {
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export function useT(): I18nValue['t'] {
  return useContext(I18nContext).t;
}

/** Theme and plugin names live in data files, so they translate by value. */
export function useLocalizedTheme() {
  const { t } = useI18n();
  return useMemo(() => (name: string) => t(name), [t]);
}

